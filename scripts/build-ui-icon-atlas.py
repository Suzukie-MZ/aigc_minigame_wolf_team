"""Package existing UI art with an embedded fallback for deployed game runtimes."""
import base64
import io
import json
import re
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
source = (ROOT / 'js/play/neutral-config.js').read_text()
manifest = json.loads(re.search(r'var manifest = (.*);', source).group(1))
icons = [item for item in manifest['assetManifest'] if item['key'].startswith('ui-')]
CELL, PAD, COLS = 128, 2, 4
rows = (len(icons) + COLS - 1) // COLS
atlas = Image.new('RGBA', (CELL * COLS, CELL * rows))
entries = []
for index, item in enumerate(icons):
    image = Image.open(ROOT / item['url']).convert('RGBA')
    image.thumbnail((CELL - PAD * 2, CELL - PAD * 2), Image.Resampling.LANCZOS)
    x = index % COLS * CELL + (CELL - image.width) // 2
    y = index // COLS * CELL + (CELL - image.height) // 2
    atlas.paste(image, (x, y))
    entries.append({'key': item['key'], 'type': 'image', 'version': 'ui-atlas-1', 'preload': True,
                    'render': {'fit': 'contain', 'region': [x / atlas.width, y / atlas.height,
                               (x + image.width) / atlas.width, (y + image.height) / atlas.height]}})
encoded = io.BytesIO()
atlas.save(encoded, format='PNG', optimize=True)
png = encoded.getvalue()
(ROOT / 'assets/Image/ui/ui-icons.png').write_bytes(png)
script = '''// Generated by scripts/build-ui-icon-atlas.py from the original UI artwork.
(function () {
  var M3=window.M3,platform=typeof ks!=='undefined'?ks:(typeof wx!=='undefined'?wx:null),
      data=__PNG_DATA__,url='data:image/png;base64,'+data,
      entries=__ENTRIES__,path,fs,i;
  // Native runtimes read a PNG file; H5 keeps a self-contained image source.
  if(platform){
    url='assets/Image/ui/ui-icons.png';
    if(platform.getFileSystemManager&&platform.env&&platform.env.USER_DATA_PATH){
      try{
        fs=platform.getFileSystemManager();path=platform.env.USER_DATA_PATH+'/m3-ui-icons-v1.png';
        fs.writeFileSync(path,data,'base64');url=path;
      }catch(error){console.warn('[UIIconAssets] PNG cache unavailable; using packaged atlas',error&&error.message);}
    }
  }
  for(i=0;i<entries.length;i+=1)entries[i].url=url;
  M3.UIIconAssets={manifest:entries};
})();
'''
script = script.replace('__PNG_DATA__', json.dumps(base64.b64encode(png).decode('ascii')))
script = script.replace('__ENTRIES__', json.dumps(entries, separators=(',', ':')))
(ROOT / 'js/render/ui-icon-assets.js').write_text(script)
print(f'Packaged {len(entries)} original icons: {len(png)} bytes PNG')
